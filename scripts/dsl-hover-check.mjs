import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { dslLibrary } from './dsl-library.mjs';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
await mkdir('.test', { recursive: true });
await build({ entryPoints: ['src/language-service.ts'], outfile: '.test/language-service.mjs', bundle: true, platform: 'node', format: 'esm', packages: 'external' });
const { SaturnLanguageService } = await import(pathToFileURL(resolve('.test/language-service.mjs')));
const service = new SaturnLanguageService(dslLibrary());
const source = `import { simulation as device, system, pipe } from '@saturn/core';
const water = system('water', 'Water');
const pump = device('P-101', 'pump', {system: 'water', at: {x: 80, y: 120}});
pump.flow;
pump.ports.inlet;
// device must not have hover docs in a comment
const literal = 'device';
`;
service.update({ 'src/plant.ts': source });
const at = source.indexOf('device(') + 2;
const ru = service.hover('src/plant.ts', at, 'ru'), en = service.hover('src/plant.ts', at, 'en');
assert(ru && en); assert(ru.documentation.length > 25); assert.notEqual(ru.documentation, en.documentation);
assert(ru.tags.some(tag => tag.name === 'example')); assert.match(ru.signature, /P-101/);
assert.match(service.hover('src/plant.ts', source.indexOf('pump.flow') + 6).signature, /SignalRef/);
assert.match(service.hover('src/plant.ts', source.indexOf('ports.inlet') + 8).signature, /TypedEndpoint/);
assert.equal(service.hover('src/plant.ts', source.indexOf('// device') + 5), null);
assert.equal(service.hover('src/plant.ts', source.indexOf("'device'") + 3), null);
const helper = `/** User docs <img src=x onerror=alert(1)>\n * @param n Count\n */\nexport function own(n: number) { return n; }`;
const entry = `import { own as local } from './helper'; local(2);`;
service.update({ 'src/plant.ts': entry, 'src/helper.ts': helper });
const user = service.hover('src/plant.ts', entry.indexOf('local(2)') + 2);
assert.match(user.documentation, /User docs <img/); assert(user.tags.some(tag => tag.name === 'param'));
const shadow = `/** Local function, not the Saturn factory. */\nfunction simulation() { return 42; }\nsimulation();`;
service.update({ 'src/plant.ts': shadow });
const shadowInfo = service.hover('src/plant.ts', shadow.lastIndexOf('simulation') + 3);
assert.equal(shadowInfo.documentation, 'Local function, not the Saturn factory.');
service.update({ 'src/plant.ts': source.replaceAll('P-101', 'P-202') });
assert.match(service.hover('src/plant.ts', at).signature, /P-202/);
service.dispose();
console.log('PASS: actual SDK types, inferred signals/ports, aliases, multi-file JSDoc, RU/EN, no false comment/string/shadow tooltips, updated documents.');
